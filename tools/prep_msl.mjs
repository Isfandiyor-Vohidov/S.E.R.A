// S.E.R.A — Safe Exploration & Return Assistant
// Written with AI assistance (Claude), reviewed by team VAA.
// prep_msl.mjs: the real Curiosity path through our EVA zone, with one Navcam photo per stop.
// Sources: NASA/JPL MMGIS (MSL_waypoints.json, MSL_traverse.json) and the NASA raw images API.
// Writes data/msl.js. Photos are not copied: the site links to the NASA raw image files.
//
// Usage:  cd tools && node prep_msl.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const MMGIS = 'https://mars.nasa.gov/mmgis-maps/MSL/Layers/json/';
const RAW_API = 'https://mars.nasa.gov/api/v1/raw_image_items/';
const PHOTO_EVERY = 3;      // a photo for every 3rd stop in the zone (keeps the request count low)

// Zone frame from data/terrain.js
const terrainSrc = readFileSync(join(here, '..', 'data', 'terrain.js'), 'utf8');
const num = (k) => Number(terrainSrc.match(new RegExp(k + ':\\s*(-?[\\d.]+)'))[1]);
const N = num('north'), W = num('west'), cellDeg = num('cellDeg'), rows = num('rows'), cols = num('cols');
const S = N - rows * cellDeg, E = W + cols * cellDeg;
const inZone = (lon, lat) => lat <= N && lat >= S && lon >= W && lon <= E;

async function getJson(url) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(url);
      if (res.ok) return await res.json();
    } catch (e) { /* retry */ }
    await new Promise((r) => setTimeout(r, 1500));
  }
  throw new Error('failed: ' + url);
}

// 1. Stops (waypoints) inside the zone
const wp = (await getJson(MMGIS + 'MSL_waypoints.json')).features.map((f) => f.properties);
const stops = wp.filter((p) => inZone(p.lon, p.lat)).map((p) => ({
  sol: p.sol, site: p.site, drive: p.drive,
  lat: +p.lat.toFixed(6), lon: +p.lon.toFixed(6), elev: +p.elev_geoid.toFixed(1)
}));
console.log('stops in zone', stops.length, 'sols', stops[0].sol, '..', stops[stops.length - 1].sol);

// 2. Traverse line clipped to the zone (pieces that stay inside)
const tr = (await getJson(MMGIS + 'MSL_traverse.json')).features;
const pieces = [];
for (const f of tr) {
  const lines = f.geometry.type === 'MultiLineString' ? f.geometry.coordinates : [f.geometry.coordinates];
  for (const line of lines) {
    let cur = [];
    for (const [lon, lat] of line) {
      if (inZone(lon, lat)) cur.push([+lat.toFixed(6), +lon.toFixed(6)]);
      else if (cur.length) { if (cur.length > 1) pieces.push(cur); cur = []; }
    }
    if (cur.length > 1) pieces.push(cur);
  }
}
// Thin the line: keep points at least ~2 m apart.
const thin = pieces.map((p) => p.filter((pt, i) => {
  if (i === 0 || i === p.length - 1) return true;
  const q = p[i - 1];
  return Math.hypot(pt[0] - q[0], pt[1] - q[1]) > 2 / 59274;   // degrees per ~2 m on Mars
}));
console.log('traverse pieces', thin.length, 'points', thin.reduce((a, p) => a + p.length, 0));

// 3. One Navcam photo per chosen stop: a full-size left Navcam frame looking near the horizon.
async function photoForSol(sol) {
  for (let page = 0; page < 4; page++) {
    const url = RAW_API + '?order=date_taken%20desc&per_page=100&page=' + page +
      '&condition_1=msl:mission&condition_2=' + sol + ':sol:gte&condition_3=' + sol + ':sol:lte';
    const d = await getJson(url);
    const nav = (d.items || []).filter((it) => it.instrument === 'NAV_LEFT_B' &&
      it.extended && it.extended.sample_type === 'full');
    const good = nav.find((it) => {
      const el = Number(it.extended.mast_el);
      return el > -25 && el < 5;
    });
    if (good) {
      return {
        full: good.https_url,
        thumb: good.https_url.replace('EDR_F', 'EDR_T'),
        lmst: (good.extended.lmst || '').replace(/^Sol-\d+M/, '').slice(0, 5),
        az: Math.round(Number(good.extended.mast_az)),
        credit: good.image_credit || 'NASA/JPL-Caltech'
      };
    }
    if (!d.more) break;
  }
  return null;
}

const chosen = stops.filter((s, i) => i % PHOTO_EVERY === 0 || i === stops.length - 1);
let found = 0;
for (const s of chosen) {
  s.photo = await photoForSol(s.sol);
  if (s.photo) found++;
  process.stdout.write(s.photo ? '+' : '.');
}
console.log('\nphotos', found, 'of', chosen.length);

const out = `// S.E.R.A — Curiosity in our EVA zone, generated by tools/prep_msl.mjs. Do not edit by hand.
// Written with AI assistance (Claude), reviewed by team VAA.
// Sources: NASA/JPL-Caltech MMGIS (MSL_waypoints.json, MSL_traverse.json);
// photos: NASA raw images API, Curiosity Navcam (NASA/JPL-Caltech), linked, not copied.
window.SERA_MSL = {
  source: 'NASA/JPL-Caltech MMGIS and raw images',
  built: '${new Date().toISOString().slice(0, 10)}',
  stops: ${JSON.stringify(stops)},
  traverse: ${JSON.stringify(thin)}
};
`;
writeFileSync(join(here, '..', 'data', 'msl.js'), out);
console.log('wrote data/msl.js', (out.length / 1024).toFixed(1), 'kB');
