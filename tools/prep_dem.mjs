// SARA — Safe Exploration & Return Assistant
// Written with AI assistance (Claude), reviewed by team VAA.
// prep_dem.mjs: cuts the EVA zone out of the USGS "Mars MSL Gale Merged DEM 1m v3"
// (Calef & Parker 2016; HiRISE + CTX + HRSC tied to MOLA) with HTTP range requests
// and writes data/terrain.js (heights on a coarser grid).
//
// Usage:  cd tools && npm install && node prep_dem.mjs
// (Python rasterio was blocked on the team laptop, so this uses geotiff.js.)

import { fromUrl } from 'geotiff';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const DEM_URL = 'https://planetarymaps.usgs.gov/mosaic/Mars/MSL/MSL_Gale_DEM_Mosaic_1m_v3.tif';

const MARS_RADIUS_M = 3396190;          // sphere used by the DEM projection
const CENTER = { lat: -4.806, lon: 137.383 }; // boxwork area, Curiosity sols ~4600-4800
const SIZE_M = 2000;                     // zone is SIZE_M x SIZE_M
const CELL_M = 5;                        // output grid step

const rad = Math.PI / 180;
// DEM projection: equirectangular, centre longitude 0, sphere R (x = R*lon, y = R*lat).
const toX = (lon) => MARS_RADIUS_M * lon * rad;
const toY = (lat) => MARS_RADIUS_M * lat * rad;

// The file is striped (one row per strip, LZW), so read in big 4 MB blocks:
// ~130 MB is downloaded for a 2 km zone, in a few dozen requests.
const tiff = await fromUrl(DEM_URL, { blockSize: 4 * 1024 * 1024, cacheSize: 80 });
const image = await tiff.getImage();
const [ox, oy] = image.getOrigin();
const [rx, ry] = image.getResolution(); // ry is negative (north up)
const nodata = image.getGDALNoData();
console.log('size', image.getWidth(), 'x', image.getHeight(), 'origin', ox, oy, 'res', rx, ry, 'nodata', nodata);
console.log('geoKeys', JSON.stringify(image.getGeoKeys()));

const cx = toX(CENTER.lon);
const cy = toY(CENTER.lat);
const half = SIZE_M / 2;
const col0 = Math.round((cx - half - ox) / rx);
const row0 = Math.round((cy + half - oy) / ry);
const nPix = Math.round(SIZE_M / Math.abs(rx));
console.log('window', col0, row0, nPix);

const [src] = await image.readRasters({ window: [col0, row0, col0 + nPix, row0 + nPix] });

// Block-average the 1 m pixels down to CELL_M cells.
const k = Math.round(CELL_M / Math.abs(rx));
const n = Math.floor(nPix / k);
const elev = new Float32Array(n * n);
let min = Infinity, max = -Infinity, holes = 0;
for (let r = 0; r < n; r++) {
  for (let c = 0; c < n; c++) {
    let sum = 0, cnt = 0;
    for (let dr = 0; dr < k; dr++) {
      for (let dc = 0; dc < k; dc++) {
        const v = src[(r * k + dr) * nPix + (c * k + dc)];
        if (Number.isFinite(v) && v !== nodata && v > -1e4 && v < 1e5) { sum += v; cnt++; }
      }
    }
    if (cnt) {
      const m = sum / cnt;
      elev[r * n + c] = m;
      if (m < min) min = m;
      if (m > max) max = m;
    } else {
      elev[r * n + c] = NaN;
      holes++;
    }
  }
}
console.log('grid', n, 'x', n, 'min', min, 'max', max, 'holes', holes);
if (holes > 0) throw new Error('DEM has holes in the zone: pick another centre');

// Heights as unsigned 16-bit decimetres above the zone minimum, base64.
const q = new Uint16Array(n * n);
for (let i = 0; i < q.length; i++) q[i] = Math.round((elev[i] - min) * 10);
const b64 = Buffer.from(q.buffer).toString('base64');

// Exact geographic frame of the cut (top-left corner of the top-left cell).
const west = (ox + col0 * rx) / MARS_RADIUS_M / rad;
const north = (oy + row0 * ry) / MARS_RADIUS_M / rad;
const cellDeg = (k * Math.abs(rx)) / MARS_RADIUS_M / rad;

const out = `// SARA — terrain data, generated by tools/prep_dem.mjs. Do not edit by hand.
// Written with AI assistance (Claude), reviewed by team VAA.
// Source: Mars MSL Gale Merged DEM 1m v3 (USGS Astrogeology; Calef & Parker 2016),
// built from MRO HiRISE, MRO CTX and Mars Express HRSC, tied to MGS MOLA.
// ${DEM_URL}
window.SERA_TERRAIN = {
  source: 'USGS MSL Gale Merged DEM 1m v3',
  cellM: ${k * Math.abs(rx)},
  rows: ${n},
  cols: ${n},
  north: ${north.toFixed(8)},
  west: ${west.toFixed(8)},
  cellDeg: ${cellDeg.toFixed(10)},
  minElevM: ${min.toFixed(2)},
  maxElevM: ${max.toFixed(2)},
  scale: 0.1,
  encoding: 'uint16le-base64, row 0 = north, value * scale + minElevM = metres (areoid)',
  data: '${b64}'
};
`;

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'data', 'terrain.js');
writeFileSync(target, out);
console.log('wrote', target, (out.length / 1024).toFixed(0), 'kB');
