// SARA — Safe Exploration & Return Assistant
// Written with AI assistance (Claude), reviewed by team VAA.
// prep_rems.mjs: downloads the Curiosity REMS weather feed (NASA/JPL-Caltech/CAB)
// and folds all sols into mean values per 10 degrees of solar longitude (Ls).
// Writes data/rems.js. Also compares our Mars clock (js/marstime.js) with the Ls
// reported by the mission for every sol.
//
// Usage:  cd tools && node prep_rems.mjs

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const MT = require('../js/marstime.js');

const URL_REMS = 'https://mars.nasa.gov/rss/api/?feed=weather&category=msl&feedtype=json';
const BIN_DEG = 10;

const res = await fetch(URL_REMS);
if (!res.ok) throw new Error('REMS feed ' + res.status);
const sols = (await res.json()).soles;

const num = (v) => (v === '--' || v === undefined || v === null || v === '' ? null : Number(v));
const bins = Array.from({ length: 360 / BIN_DEG }, () => ({
  n: 0, minT: [], maxT: [], p: [], minG: [], maxG: []
}));

let lsDiffSum = 0, lsDiffMax = 0, lsN = 0, firstDate = null, lastDate = null, lastSol = 0;
for (const s of sols) {
  const ls = num(s.ls);
  if (ls === null) continue;
  const b = bins[Math.floor((ls % 360) / BIN_DEG)];
  b.n++;
  const push = (arr, v) => { if (v !== null && Number.isFinite(v)) arr.push(v); };
  push(b.minT, num(s.min_temp));
  push(b.maxT, num(s.max_temp));
  push(b.p, num(s.pressure));
  push(b.minG, num(s.min_gts_temp));
  push(b.maxG, num(s.max_gts_temp));

  // Validation of marstime.js: Ls at noon UTC of the same Earth date.
  const utc = Date.parse(s.terrestrial_date + 'T12:00:00Z');
  if (Number.isFinite(utc)) {
    let diff = Math.abs(MT.marsClock(utc).ls - ls);
    if (diff > 180) diff = 360 - diff;
    lsDiffSum += diff; lsN++;
    if (diff > lsDiffMax) lsDiffMax = diff;
    if (!firstDate || s.terrestrial_date < firstDate) firstDate = s.terrestrial_date;
    if (!lastDate || s.terrestrial_date > lastDate) lastDate = s.terrestrial_date;
    if (Number(s.sol) > lastSol) lastSol = Number(s.sol);
  }
}

const mean = (a) => (a.length ? Math.round((a.reduce((x, y) => x + y, 0) / a.length) * 10) / 10 : null);
const rows = bins.map((b, i) => ({
  ls: i * BIN_DEG,          // bin start, degrees
  sols: b.n,                // sols of data in the bin
  airMinC: mean(b.minT),    // mean daily minimum air temperature
  airMaxC: mean(b.maxT),    // mean daily maximum air temperature
  groundMinC: mean(b.minG),
  groundMaxC: mean(b.maxG),
  pressurePa: mean(b.p)
}));

const lsMean = lsDiffSum / lsN;
console.log('sols', sols.length, 'dates', firstDate, '..', lastDate, 'last sol', lastSol);
console.log('Ls check vs marstime.js: mean |diff|', lsMean.toFixed(3), 'deg, max', lsDiffMax.toFixed(3), 'deg over', lsN, 'sols');
console.table(rows.filter((_, i) => i % 6 === 0));

const out = `// SARA — Gale Crater weather climatology, generated by tools/prep_rems.mjs. Do not edit by hand.
// Written with AI assistance (Claude), reviewed by team VAA.
// Source: Curiosity REMS daily weather reports (NASA/JPL-Caltech/CAB(CSIC-INTA)),
// ${URL_REMS}
// ${sols.length} sols, ${firstDate} to ${lastDate}, folded into ${BIN_DEG} degree Ls bins (mean values).
window.SERA_REMS = {
  source: 'Curiosity REMS',
  sols: ${sols.length},
  firstDate: '${firstDate}',
  lastDate: '${lastDate}',
  lastSol: ${lastSol},
  binDeg: ${BIN_DEG},
  lsCheck: { meanAbsDiffDeg: ${lsMean.toFixed(3)}, maxAbsDiffDeg: ${lsDiffMax.toFixed(3)}, sols: ${lsN} },
  bins: ${JSON.stringify(rows)}
};
`;
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, '..', 'data', 'rems.js'), out);
console.log('wrote data/rems.js', (out.length / 1024).toFixed(1), 'kB');
