# S.E.R.A — Safe Exploration & Return Assistant
# Written with AI assistance (Claude), reviewed by team VAA.
# prep_places.py: the official names of places on Mars (IAU nomenclature, 1,783 features) from the
# NASA Mars Trek catalog, for the "Find a place" search of the planner. The search then works
# offline and needs no request to Trek (its search service does not allow other websites).
# Writes data/places.js:  [name, feature type, lat, east lon]
#
# Usage:  python tools/prep_places.py

import json
import os
import re
import urllib.request

URL = ('https://trek.nasa.gov/mars/TrekServices/ws/index/eq/searchItems?start=0&rows=2500'
       '&itemType=nomenclature&proj=urn:ogc:def:crs:EPSG::104905')
HERE = os.path.dirname(os.path.abspath(__file__))

with urllib.request.urlopen(URL, timeout=120) as r:
    docs = json.load(r)['response']['docs']

rows = []
for d in docs:
    if d.get('itemType') != 'nomenclature':
        continue
    m = re.match(r'POINT \((-?[\d.]+) (-?[\d.]+)\)', d.get('shape', ''))
    if not m:
        continue
    lon, lat = float(m.group(1)), float(m.group(2))
    kind = (d.get('productCat2') or '').split(',')[0].strip()
    rows.append([d['title'], kind, round(lat, 3), round(lon, 3)])
rows.sort(key=lambda x: x[0])

out = ('// S.E.R.A — official names of places on Mars, generated by tools/prep_places.py. Do not edit by hand.\n'
       '// Written with AI assistance (Claude), reviewed by team VAA.\n'
       '// Source: IAU / USGS Gazetteer of Planetary Nomenclature via NASA Mars Trek. [name, type, lat, east lon]\n'
       'window.SERA_PLACES = ' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n')
open(os.path.join(HERE, '..', 'data', 'places.js'), 'w', encoding='utf-8').write(out)
print(len(rows), 'places,', round(len(out) / 1024), 'kB')
